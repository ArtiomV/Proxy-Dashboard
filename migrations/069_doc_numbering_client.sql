-- 2026-08-17: поклиентская сквозная нумерация «№ NN/MM-YYYY» — счётчик
-- непрерывный с момента начала работы с клиентом (НЕ сбрасывается каждый
-- месяц), а MM-YYYY в метке — месяц периода документа. Единая серия актов и
-- счетов внутри клиента: по номеру видно, какой это по счёту документ
-- клиента, а по суффиксу — за какой месяц. Номера не переиспользуются.
-- doc_numbering_monthly (068) остаётся как архив выданных ранее номеров.
CREATE TABLE IF NOT EXISTS doc_numbering_client (
  client_id TEXT PRIMARY KEY,
  next_num INTEGER NOT NULL DEFAULT 1
);
