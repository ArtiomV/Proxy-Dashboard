-- 2026-10-03: ip_history перестаёт быть «последние 100 назначений на модем».
-- Раньше recordIpChange удалял из таблицы всё сверх MAX_IP_HISTORY=100 —
-- для модема с ротацией раз в ~10 мин это ~17 часов истории, и аналитика
-- /api/analytics/ip_stats «за 30 дней» показывала 80–100 уникальных IP
-- вместо реальных тысяч (расхождение с клиентской карточкой, которая
-- считает distinct new_ip из rotation_log). Теперь история хранится 90 дней
-- с retention-пургой, а кап 100 остаётся только для in-memory кэша.
-- Индекс нужен, т.к. все ip_stats-запросы фильтруют по started_at, а таблица
-- перестанет быть маленькой.
CREATE INDEX IF NOT EXISTS idx_ip_history_started ON ip_history(started_at);
