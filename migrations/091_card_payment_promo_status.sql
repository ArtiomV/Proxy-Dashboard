-- 2026-09-18 · DEEP-02 / FIX-SPEC §14.2: статус промобонуса отделён от статуса
-- основной оплаты. Проблема бонуса (код отключён/исчерпан/удалён после оплаты)
-- не прячет факт оплаты и не крутит заказ в recovery бесконечно.
--   promo_status: NULL — без промокода / legacy-строки (сверяются по ledger в
--                 рантайме); 'applied' — бонус зачислен; 'review' — бонус ушёл
--                 на ручную сверку (деньги основной оплаты уже у клиента).
--   promo_bonus_amount — сумма бонуса, зафиксированная при создании заказа:
--                 последующее редактирование/удаление/пересоздание промокода
--                 не меняет подтверждённое обязательство.
-- Исторические строки намеренно НЕ переписываются: promo_status для них
-- вычисляется сверкой ledger при первом обращении (деньги не трогаем вслепую).
ALTER TABLE card_payments ADD COLUMN promo_status TEXT;
ALTER TABLE card_payments ADD COLUMN promo_bonus_amount REAL;

