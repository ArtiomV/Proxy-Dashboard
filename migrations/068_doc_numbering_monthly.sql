-- 2026-08-17: новая модель нумерации «№ N/MM-YYYY» — счётчик привязан к
-- МЕСЯЦУ, к которому относится документ (period), а не к дате создания.
-- Серия актов и счетов по-прежнему единая (один счётчик на месяц), номера
-- не переиспользуются, старые документы «N/YYYY» не перенумеровываются.
-- Старая таблица doc_numbering (годовая серия) остаётся как архив — новые
-- номера выдаются из doc_numbering_monthly.
CREATE TABLE IF NOT EXISTS doc_numbering_monthly (
  ym       TEXT PRIMARY KEY,          -- 'YYYY-MM' месяца периода документа
  next_num INTEGER NOT NULL DEFAULT 1
);
