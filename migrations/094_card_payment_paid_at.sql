-- незавершённого зачисления (paid → credited) считается от paid_at, а не от
-- created_at: заказ мог быть создан задолго до реальной оплаты.
-- Историческим строкам время оплаты задним числом НЕ приписывается: paid_at
-- остаётся NULL — это диагностируемое состояние (recovery логирует его),
-- а не повод считать возраст от даты создания заказа.
ALTER TABLE card_payments ADD COLUMN paid_at TEXT;
